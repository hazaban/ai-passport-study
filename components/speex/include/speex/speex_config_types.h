/* speex_config_types.h — 由 configure 生成的类型映射，这里手工提供。
 * ESP32-C3 (Xtensa GCC)：int16/int32 直接映射到标准 C 类型。 */
#ifndef __SPEEX_CONFIG_TYPES_H
#define __SPEEX_CONFIG_TYPES_H

#include <stdint.h>

typedef int16_t  spx_int16_t;
typedef uint16_t spx_uint16_t;
typedef int32_t  spx_int32_t;
typedef uint32_t spx_uint32_t;

#endif /* __SPEEX_CONFIG_TYPES_H */